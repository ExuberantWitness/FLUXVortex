"""Freeze local full-resolution phase histories for Scherer Figure 14.

The public Figure-14 evidence contains cycle-mean thrust only.  This cache is
therefore *not* experimental phase truth: it stores three local model phase
histories needed by later causal diagnostics.  Histories are generated by the
existing ``run_izraelevitz_scherer_experiment._condition_history`` function,
with its full 4x12 grid, four cycles, 128 samples per cycle and Cd0=0.057 load
ledger.  No LDVM/v4 force correction is called here.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import time
from pathlib import Path
from typing import Any

import numpy as np

from .cases import IZRAELEVITZ_2017_FIG14_SCHERER as CASE
from .run_izraelevitz_scherer_experiment import (
    DEFAULT_SOURCE,
    _condition_history,
)


REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_CSV = (
    REPO_ROOT / "docs/forward_flight_large_pitch/reproductions/"
    "unified_fluxv_v4_ldvm_stevens_20260812/source_data/"
    "izraelevitz2017_fig14_local_phase_cache.csv"
)
MODELS = ("fluxv_uvpm", "one_state_ullt_local", "fluxv_periodic_v1")
EXPECTED_CONDITIONS = (
    (15.0, 15.0),
    (15.0, 30.0),
    (15.0, 45.0),
    (15.0, 60.0),
    (15.0, 75.0),
    (15.0, 90.0),
    (15.0, 105.0),
    (25.0, 45.0),
    (25.0, 60.0),
    (25.0, 75.0),
    (25.0, 90.0),
    (25.0, 105.0),
)
FIELDNAMES = (
    "model",
    "theta_max_deg",
    "phase_offset_deg",
    "phase",
    "lift_n",
    "drag_n",
    "CL",
    "CD",
    "CT",
)
SAMPLES_PER_HISTORY = 128


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _relative(path: Path) -> str:
    return path.resolve().relative_to(REPO_ROOT).as_posix()


def _source_conditions(path: Path = DEFAULT_SOURCE) -> tuple[tuple[float, float], ...]:
    with path.open(newline="", encoding="utf-8") as stream:
        observations = [
            row
            for row in csv.DictReader(stream)
            if row["data_role"] == "experimental_observation"
        ]
    conditions = tuple(
        sorted(
            {
                (float(row["theta_max_deg"]), float(row["phase_offset_deg"]))
                for row in observations
            }
        )
    )
    if conditions != EXPECTED_CONDITIONS:
        raise ValueError(
            "Scherer condition set changed; refusing to silently regenerate "
            f"the frozen cache: {conditions!r}"
        )
    return conditions


def _history_rows(
    theta_max_deg: float,
    phase_offset_deg: float,
    histories: dict[str, dict[str, Any]],
    audit: dict[str, Any],
) -> list[dict[str, Any]]:
    if int(audit["output_samples"]) != SAMPLES_PER_HISTORY:
        raise ValueError(
            f"full condition emitted {audit['output_samples']} samples, expected 128"
        )
    movement = audit["movement"]
    if int(movement["requested_steps_per_cycle"]) != SAMPLES_PER_HISTORY:
        raise ValueError("full Scherer movement is not configured for 128 steps/cycle")
    if movement["grid_chord_semispan"] != [4, 12]:
        raise ValueError(
            "full Scherer movement grid changed from the frozen [4, 12] contract"
        )
    if int(movement["cycles"]) != 4:
        raise ValueError("full Scherer movement must use four cycles")

    rows: list[dict[str, Any]] = []
    expected_phase = np.arange(SAMPLES_PER_HISTORY, dtype=float) / SAMPLES_PER_HISTORY
    q_area = 0.5 * CASE.rho_kg_m3 * CASE.freestream_m_s**2 * CASE.area_m2
    for model in MODELS:
        history = histories[model]
        arrays = {
            key: np.asarray(history[key], dtype=float)
            for key in ("phase", "lift_n", "drag_n", "CL", "CD", "CT")
        }
        if any(values.shape != (SAMPLES_PER_HISTORY,) for values in arrays.values()):
            shapes = {key: values.shape for key, values in arrays.items()}
            raise ValueError(f"unexpected {model} history shapes: {shapes}")
        if not np.allclose(arrays["phase"], expected_phase, rtol=0.0, atol=1.0e-12):
            raise ValueError(f"{model} phase grid is not j/128")
        if not np.all(np.isfinite(sum(arrays.values()))):
            raise FloatingPointError(f"{model} contains non-finite phase loads")
        if not np.allclose(
            arrays["lift_n"] / q_area,
            arrays["CL"],
            rtol=5.0e-12,
            atol=5.0e-12,
        ):
            raise ValueError(f"{model} lift coefficient ledger is inconsistent")
        if not np.allclose(
            arrays["drag_n"] / q_area,
            arrays["CD"],
            rtol=5.0e-12,
            atol=5.0e-12,
        ):
            raise ValueError(f"{model} drag coefficient ledger is inconsistent")
        if not np.allclose(arrays["CT"], -arrays["CD"], rtol=0.0, atol=5.0e-12):
            raise ValueError(f"{model} CT=-CD sign contract is inconsistent")
        for index in range(SAMPLES_PER_HISTORY):
            rows.append(
                {
                    "model": model,
                    "theta_max_deg": theta_max_deg,
                    "phase_offset_deg": phase_offset_deg,
                    "phase": arrays["phase"][index],
                    "lift_n": arrays["lift_n"][index],
                    "drag_n": arrays["drag_n"][index],
                    "CL": arrays["CL"][index],
                    "CD": arrays["CD"][index],
                    "CT": arrays["CT"][index],
                }
            )
    return rows


def _read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as stream:
        reader = csv.DictReader(stream)
        if tuple(reader.fieldnames or ()) != FIELDNAMES:
            raise ValueError(f"unexpected cache fields: {reader.fieldnames!r}")
        return list(reader)


def _write_atomic(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDNAMES, extrasaction="raise")
        writer.writeheader()
        writer.writerows(rows)
    temporary.replace(path)


def validate_cache(path: Path, *, require_complete: bool = True) -> dict[str, Any]:
    rows = _read_rows(path)
    groups: dict[tuple[float, float, str], list[dict[str, str]]] = {}
    for row in rows:
        key = (
            float(row["theta_max_deg"]),
            float(row["phase_offset_deg"]),
            row["model"],
        )
        groups.setdefault(key, []).append(row)
    for key, group in groups.items():
        if key[:2] not in EXPECTED_CONDITIONS:
            raise ValueError(f"unexpected condition in cache: {key[:2]}")
        if key[2] not in MODELS:
            raise ValueError(f"unexpected model in cache: {key[2]}")
        if len(group) != SAMPLES_PER_HISTORY:
            raise ValueError(f"{key} has {len(group)} samples, expected 128")
        phase = np.asarray([float(row["phase"]) for row in group])
        if not np.allclose(
            phase,
            np.arange(SAMPLES_PER_HISTORY) / SAMPLES_PER_HISTORY,
            rtol=0.0,
            atol=1.0e-12,
        ):
            raise ValueError(f"{key} phase grid is not ordered j/128")
        numeric = np.asarray(
            [[float(row[field]) for field in FIELDNAMES[3:]] for row in group]
        )
        if not np.all(np.isfinite(numeric)):
            raise FloatingPointError(f"{key} contains non-finite values")
        if not np.allclose(numeric[:, -1], -numeric[:, -2], atol=5.0e-12):
            raise ValueError(f"{key} violates CT=-CD")

    completed_conditions = sorted({key[:2] for key in groups})
    if require_complete:
        expected_groups = {
            (theta, phase_offset, model)
            for theta, phase_offset in EXPECTED_CONDITIONS
            for model in MODELS
        }
        if set(groups) != expected_groups:
            missing = sorted(expected_groups.difference(groups))
            extra = sorted(set(groups).difference(expected_groups))
            raise ValueError(f"cache group mismatch; missing={missing}, extra={extra}")
        expected_rows = len(EXPECTED_CONDITIONS) * len(MODELS) * SAMPLES_PER_HISTORY
        if len(rows) != expected_rows:
            raise ValueError(f"cache has {len(rows)} rows, expected {expected_rows}")
    return {
        "path": _relative(path),
        "sha256": _sha256(path),
        "row_count": len(rows),
        "condition_count": len(completed_conditions),
        "models": list(MODELS),
        "samples_per_history": SAMPLES_PER_HISTORY,
        "complete": len(completed_conditions) == len(EXPECTED_CONDITIONS),
    }


def run() -> dict[str, Any]:
    conditions = _source_conditions()
    partial = OUTPUT_CSV.with_suffix(".partial.csv")
    rows: list[dict[str, Any]] = []
    completed: set[tuple[float, float]] = set()
    if partial.exists():
        rows = list(_read_rows(partial))
        partial_summary = validate_cache(partial, require_complete=False)
        groups = {
            (float(row["theta_max_deg"]), float(row["phase_offset_deg"]))
            for row in rows
        }
        completed = set(groups)
        print(
            json.dumps({"event": "resume", **partial_summary}, sort_keys=True),
            flush=True,
        )

    total_start = time.perf_counter()
    for condition_index, (theta, phase_offset) in enumerate(conditions, start=1):
        if (theta, phase_offset) in completed:
            continue
        started = time.perf_counter()
        histories, audit = _condition_history(theta, phase_offset, "full")
        rows.extend(_history_rows(theta, phase_offset, histories, audit))
        _write_atomic(partial, rows)
        progress = {
            "event": "condition_complete",
            "condition_index": condition_index,
            "condition_count": len(conditions),
            "theta_max_deg": theta,
            "phase_offset_deg": phase_offset,
            "elapsed_condition_s": time.perf_counter() - started,
            "elapsed_total_s": time.perf_counter() - total_start,
            "partial_sha256": _sha256(partial),
        }
        print(json.dumps(progress, sort_keys=True), flush=True)

    validate_cache(partial, require_complete=True)
    partial.replace(OUTPUT_CSV)
    summary = validate_cache(OUTPUT_CSV, require_complete=True)
    summary.update(
        {
            "condition_source": _relative(DEFAULT_SOURCE),
            "condition_source_sha256": _sha256(DEFAULT_SOURCE),
            "runner": _relative(Path(__file__)),
            "runner_sha256": _sha256(Path(__file__)),
            "runtime_s": time.perf_counter() - total_start,
            "quality": "full",
            "grid_chord_semispan": [4, 12],
            "cycles": 4,
        }
    )
    print(json.dumps(summary, indent=2, sort_keys=True), flush=True)
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--validate-only",
        action="store_true",
        help="validate the fixed cache without rerunning the aerodynamic models",
    )
    arguments = parser.parse_args()
    if arguments.validate_only:
        print(
            json.dumps(
                validate_cache(OUTPUT_CSV, require_complete=True),
                indent=2,
                sort_keys=True,
            )
        )
    else:
        run()


if __name__ == "__main__":
    main()
