"""Frozen Yamano 2020 single-sheet inputs for the Q16 FSI reproduction.

The reference files are the outputs and parameter deck distributed with the
authors' public ``FSI_by_FEM_and_UVLM`` MATLAB implementation.  This adapter
owns dimensionalization, Q16 topology, leading-edge constraints and surface
coordinates; it does not tune any material value against observed responses.

The repository's historical ``save/tip_displacement.csv`` is deliberately not
used as a response oracle: its export expression indexes ``h_X_vec`` as if a
node had three DOFs, although the ANCF state has nine DOFs per node.  The
correct reference below was extracted from the preserved MATLAB ``h_X_vec``
fixture with ``node*9 + z`` and is independently hash frozen.
"""

