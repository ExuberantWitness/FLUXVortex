def _sha256(path: Path) -> str:
    if not path.is_file():
        raise FileNotFoundError(path)
    return hashlib.sha256(path.read_bytes()).hexdigest()


def validate_yamano2020_sources() -> None:
    expected = (
        (PARAMETER_DECK, PARAMETER_DECK_SHA256),
        (TIP_DISPLACEMENT_GENERATOR, TIP_DISPLACEMENT_GENERATOR_SHA256),
        (NATURAL_FREQUENCY_REFERENCE, NATURAL_FREQUENCY_SHA256),
        (TIP_DISPLACEMENT_REFERENCE, TIP_DISPLACEMENT_SHA256),
        (MF1_STEP1_ORACLE, MF1_STEP1_ORACLE_SHA256),
        (MF2_HISTORY_ORACLE, MF2_HISTORY_ORACLE_SHA256),
    )
    for path, digest in expected:
        observed = _sha256(path)
        if observed != digest:
            raise RuntimeError(
                f"Yamano source drift for {path.relative_to(ROOT)}: {observed}"
            )


@dataclass(frozen=True, slots=True)
class Yamano2020SingleSheetCase:
    paper_title: str = "Influence of boundary conditions on a flutter-mill"
    doi: str = "10.1016/j.jsv.2020.115359"
    case_id: str = "single_sheet_u25_m1_ar1"
    length_m: float = 1.0
    width_m: float = 1.0
    thickness_m: float = 1.0e-3
    poisson_ratio: float = 0.3
    reduced_velocity: float = 25.0
    mass_ratio: float = 1.0
    freestream_m_s: float = 10.0
    fluid_density_kg_m3: float = 1.225
    # The response oracle is generated by dump_traj_long.m, which explicitly
    # freezes d_t=2e-3.  The separate modal parameter deck uses 1.5e-3, but a
    # time step is not a material property and must not be mixed into this
    # response-lineage reproduction.
    structural_dt_star: float = 2.0e-3
    pulse_duration_star: float = 0.2
    pulse_peak_nondimensional: float = 0.5
    reference_chordwise_elements: int = 15
    reference_spanwise_elements: int = 10
    wake_truncation_chords: float = 5.5

    @property
    def solid_density_kg_m3(self) -> float:
        return (
            self.mass_ratio
            * self.fluid_density_kg_m3
            * self.length_m
            / self.thickness_m
        )

    @property
    def young_modulus_pa(self) -> float:
        return (
            12.0
            * self.solid_density_kg_m3
            * self.length_m**2
            * self.freestream_m_s**2
            / (self.reduced_velocity**2 * self.thickness_m**2)
        )

    @property
    def structural_dt_s(self) -> float:
        return self.structural_dt_star * self.length_m / self.freestream_m_s

    @property
    def structural_substeps_per_aerodynamic_step(self) -> int:
        wake_dt_star = 1.0 / self.reference_chordwise_elements
        return math.ceil(wake_dt_star / self.structural_dt_star)

    @property
    def aerodynamic_dt_star(self) -> float:
        return self.structural_substeps_per_aerodynamic_step * self.structural_dt_star

    @property
    def aerodynamic_dt_s(self) -> float:
        return self.aerodynamic_dt_star * self.length_m / self.freestream_m_s

    @property
    def pulse_duration_s(self) -> float:
        return self.pulse_duration_star * self.length_m / self.freestream_m_s

    def pulse_nondimensional_at_time_s(self, endpoint_time_s: float) -> float:
        if isinstance(endpoint_time_s, bool) or not isinstance(
            endpoint_time_s, (int, float, np.integer, np.floating)
        ):
            raise TypeError("endpoint_time_s must be a real scalar")
        time_s = float(endpoint_time_s)
        if not math.isfinite(time_s) or time_s < 0.0:
            raise ValueError("endpoint_time_s must be finite and non-negative")
        time_star = time_s * self.freestream_m_s / self.length_m
        if time_star >= self.pulse_duration_star:
            return 0.0
        return self.pulse_peak_nondimensional * math.sin(
            math.pi * time_star / self.pulse_duration_star
        )

    def pulse_body_force_density_n_m3(self, endpoint_time_s: float) -> float:
        return (
            self.pulse_nondimensional_at_time_s(endpoint_time_s)
            * self.fluid_density_kg_m3
            * self.freestream_m_s**2
            / self.thickness_m
        )


YAMANO_2020_SINGLE_SHEET = Yamano2020SingleSheetCase()


def load_nondimensional_natural_frequencies() -> np.ndarray:
    validate_yamano2020_sources()
    values: list[float] = []
    with NATURAL_FREQUENCY_REFERENCE.open(newline="") as stream:
        rows = csv.DictReader(stream)
        if rows.fieldnames != ["Mode", "Omega"]:
            raise RuntimeError("Yamano natural-frequency schema drift")
        for expected_mode, row in enumerate(rows, start=1):
            if int(row["Mode"]) != expected_mode:
                raise RuntimeError("Yamano natural-frequency mode order drift")
            value = float(row["Omega"])
            if not math.isfinite(value) or value <= 0.0:
                raise RuntimeError("Yamano natural frequency is invalid")
            values.append(value)
    result = np.ascontiguousarray(values, dtype=np.float64)
    if result.shape != (5,) or not bool(np.all(result[1:] > result[:-1])):
        raise RuntimeError("Yamano natural-frequency vector drift")
    result.setflags(write=False)
    return result


def load_tip_displacement_reference() -> np.ndarray:
    validate_yamano2020_sources()
    values: list[tuple[float, float]] = []
    with TIP_DISPLACEMENT_REFERENCE.open(newline="") as stream:
        rows = csv.DictReader(stream)
        if rows.fieldnames != ["Time", "Z_tip"]:
            raise RuntimeError("Yamano tip-displacement schema drift")
        for row in rows:
            time_star = float(row["Time"])
            displacement_star = float(row["Z_tip"])
            if (
                not math.isfinite(time_star)
                or not math.isfinite(displacement_star)
                or time_star < 0.0
            ):
                raise RuntimeError("Yamano tip-displacement value is invalid")
            values.append((time_star, displacement_star))
    result = np.ascontiguousarray(values, dtype=np.float64)
    if (
        result.shape != (501, 2)
        or result[0, 0] != 0.0
        or result[-1, 0] != 1.0
        or not bool(np.all(result[1:, 0] > result[:-1, 0]))
        or not bool(np.allclose(np.diff(result[:, 0]), 2.0e-3, rtol=0.0, atol=1e-15))
    ):
        raise RuntimeError("Yamano tip-displacement series drift")
    result.setflags(write=False)
    return result


def load_mf1_step1_oracle() -> dict[str, np.ndarray]:
    """Load the reduced MATLAB step-one Mf1 oracle for CUDA-side scoring.

    NumPy is used only as a serialized-data ingress.  The modal products and
    comparisons consuming these arrays are required to run on CUDA float64.
    """

    validate_yamano2020_sources()
    with np.load(MF1_STEP1_ORACLE, allow_pickle=False) as archive:
        result = {name: np.array(archive[name], copy=True) for name in archive.files}
    if str(result["schema"].item()) != "yamano2020-matlab-mf1-step1-oracle-v3":
        raise RuntimeError("Yamano Mf1 oracle schema drift")
    if str(result["source_sha256"].item()) != MF1_STEP1_SOURCE_FIXTURE_SHA256:
        raise RuntimeError("Yamano Mf1 source-fixture provenance drift")
    shape = tuple(int(value) for value in result["matrix_shape"].tolist())
    if shape != (1584, 1584):
        raise RuntimeError("Yamano Mf1 oracle matrix shape drift")
    if result["phi_dq"].shape != (1584, 5):
        raise RuntimeError("Yamano Mf1 oracle modal basis drift")
    if result["pulse_q"].shape != (1584,):
        raise RuntimeError("Yamano Mf1 oracle pulse vector drift")
    if result["aic"].shape != (150, 150):
        raise RuntimeError("Yamano Mf1 oracle AIC drift")
    if result["neumann"].shape != (150, 1584):
        raise RuntimeError("Yamano Mf1 oracle Neumann map drift")
    if result["gamma_rate"].shape != (150, 1584):
        raise RuntimeError("Yamano Mf1 oracle gamma-rate map drift")
    if result["free_dofs"].shape != (1485,):
        raise RuntimeError("Yamano Mf1 oracle boundary topology drift")
    for value in result.values():
        if isinstance(value, np.ndarray):
            value.setflags(write=False)
    return result


def load_mf2_history_oracle() -> dict[str, np.ndarray]:
    """Load the four-step MATLAB wake-motion oracle for CUDA-side scoring."""

    validate_yamano2020_sources()
    with np.load(MF2_HISTORY_ORACLE, allow_pickle=False) as archive:
        result = {name: np.array(archive[name], copy=True) for name in archive.files}
    if str(result["schema"].item()) != "yamano2020-matlab-mf2-history-oracle-v1":
        raise RuntimeError("Yamano Mf2 history oracle schema drift")
    if int(result["step_count"].item()) != 4:
        raise RuntimeError("Yamano Mf2 history step count drift")
    source_manifest = str(result["source_manifest_json"].item())
    for digest in MF2_HISTORY_SOURCE_FIXTURE_SHA256:
        if digest not in source_manifest:
            raise RuntimeError("Yamano Mf2 source-fixture provenance drift")
    for step, wake_count in enumerate((20, 30, 40, 50), start=1):
        expected_shapes = {
            "rc_vec": (150, 3),
            "dt_rc_vec": (150, 3),
            "Gamma_wake": (wake_count,),
            "n_vec_i": (150, 3),
            "A_mat": (150, 150),
            "Gamma_wake_dt_q1234_n": (150,),
            "Mf2_vec1": (150,),
            "dp_lift1": (150,),
            "Qf_p_global": (1584,),
        }
        for corner in range(1, 5):
            expected_shapes[f"r_wake_{corner}"] = (wake_count, 3)
            expected_shapes[f"dt_r_wake_{corner}"] = (wake_count, 3)
        for name, shape in expected_shapes.items():
            value = result[f"step_{step}_{name}"]
            if value.shape != shape or not bool(np.isfinite(value).all()):
                raise RuntimeError(
                    f"Yamano Mf2 history shape/value drift at step {step}: {name}"
                )
    for value in result.values():
        if isinstance(value, np.ndarray):
            value.setflags(write=False)
    return result


def make_yamano2020_q16_model(
    *,
    chordwise_element_count: int,
    spanwise_element_count: int,
    case: Yamano2020SingleSheetCase = YAMANO_2020_SINGLE_SHEET,
) -> tuple[Q16Mesh, Q16MITC16EASMesh, Q16BoundaryConstraints]:
    if type(case) is not Yamano2020SingleSheetCase:
        raise TypeError("case must be an exact Yamano2020SingleSheetCase")
    mesh = make_rectangular_q16_mesh(
        chordwise_element_count=chordwise_element_count,
        spanwise_element_count=spanwise_element_count,
        chord=case.length_m,
        span=case.width_m,
        thickness=case.thickness_m,
    )
    model = Q16MITC16EASMesh(
        mesh,
        young_modulus=case.young_modulus_pa,
        poisson_ratio=case.poisson_ratio,
        density=case.solid_density_kg_m3,
    )
    scale = max(case.length_m, 1.0)
    tolerance = 256.0 * np.finfo(np.float64).eps * scale
    leading_edge_nodes = np.flatnonzero(np.abs(mesh.reference_rows[:, 0]) <= tolerance)
    leading_edge_nodes = np.ascontiguousarray(leading_edge_nodes, dtype=np.int64)
    constraints = make_clamped_q16_nodes(mesh, leading_edge_nodes)
    return mesh, model, constraints


def _axis_owner(value: float, element_count: int) -> tuple[int, float]:
    scaled = value * element_count
    owner = min(int(math.floor(scaled)), element_count - 1)
    local = 2.0 * (scaled - owner) - 1.0
    tolerance = 128.0 * np.finfo(np.float64).eps
    if local < -1.0 - tolerance or local > 1.0 + tolerance:
        raise RuntimeError("Yamano surface coordinate left its Q16 owner")
    return owner, min(max(local, -1.0), 1.0)


def make_yamano2020_surface_transfer_map(
    mesh: Q16Mesh,
    *,
    q16_chordwise_element_count: int,
    q16_spanwise_element_count: int,
    aerodynamic_chordwise_panel_count: int,
    aerodynamic_spanwise_panel_count: int,
) -> Q16SurfaceTransferMap:
    for name, value in (
        ("q16_chordwise_element_count", q16_chordwise_element_count),
        ("q16_spanwise_element_count", q16_spanwise_element_count),
        ("aerodynamic_chordwise_panel_count", aerodynamic_chordwise_panel_count),
        ("aerodynamic_spanwise_panel_count", aerodynamic_spanwise_panel_count),
    ):
        if type(value) is not int or value <= 0:
            raise ValueError(f"{name} must be a positive exact int")
    if mesh.element_count != (q16_chordwise_element_count * q16_spanwise_element_count):
        raise ValueError("Q16 element counts differ from mesh ownership")
    element_indices: list[int] = []
    coordinates: list[tuple[float, float, float]] = []
    for chord_vertex in range(aerodynamic_chordwise_panel_count + 1):
        chord_fraction = chord_vertex / aerodynamic_chordwise_panel_count
        chord_owner, xi = _axis_owner(chord_fraction, q16_chordwise_element_count)
        for span_vertex in range(aerodynamic_spanwise_panel_count + 1):
            span_fraction = span_vertex / aerodynamic_spanwise_panel_count
            span_owner, eta = _axis_owner(span_fraction, q16_spanwise_element_count)
            element_indices.append(
                span_owner * q16_chordwise_element_count + chord_owner
            )
            coordinates.append((xi, eta, 0.0))
    return Q16SurfaceTransferMap(
        mesh=mesh,
        element_indices=np.ascontiguousarray(element_indices, dtype=np.int64),
        parametric_coordinates=np.ascontiguousarray(coordinates, dtype=np.float64),
    )


